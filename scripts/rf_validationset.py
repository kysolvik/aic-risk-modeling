#Validation Set

import ee
from inputBands_Generator import create_inputBands
ee.Authenticate()
ee.Initialize(project='macedo-lab-general-9051')
area = ee.FeatureCollection('projects/ksolvik-misc/assets/Lim_Raisg')
amazonBounds = area.geometry().simplify(1000) #I had to simplify the area because stratified sampling was failing on the initial complex area

startYears = ee.List([2018, 2019, 2020, 2021, 2022, 2023])

def extractPointsForYear(year):
    currentYear = ee.Number(year)

    imageFinale, target = create_inputBands(year)

    finalPoints = imageFinale.sample(
        region=amazonBounds,
        scale=500,
        numPixels=10000,
        geometries=True
    )

    return finalPoints.map(lambda f: f.set('year', currentYear))


# Extraction loop
listDeCollections = startYears.map(lambda year: extractPointsForYear(year))
allTrainingPoints = ee.FeatureCollection(listDeCollections).flatten()

# EXPORT
task = ee.batch.Export.table.toAsset(
    collection=allTrainingPoints,
    description='Amazon_ValidationSet',
    assetId='projects/columbia-research-project/assets/ValidationSet' #Feel free to change the name
)

task.start()

